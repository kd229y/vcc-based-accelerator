"""Generate rtl/panda_consts.v from the package's build/panda_generated.hh (pinned Panda URDF/SRDF constants)."""
from pathlib import Path
import re

HW = Path(__file__).resolve().parents[1]
HDR = HW.parent / 'SoC_軟體驗證資料包' / 'build' / 'panda_generated.hh'


def ints(s):
    return [int(v) for v in re.findall(r'-?\d+', s)]


def main():
    text = HDR.read_text()
    joints_blk = text[text.index('JOINTS[NJ]={'):text.index('};', text.index('JOINTS[NJ]={'))]
    joints = []
    for line in joints_blk.splitlines()[1:]:
        line = line.strip()
        if not line.startswith('{'): continue
        # {parent,child,index,{r9},{t3},{rf9},{tf3}}
        head = line[1:line.index('{', 1)]
        p, c, idx = ints(head)[:3]
        groups = re.findall(r'\{([^{}]*)\}', line)
        r = ints(groups[0]); t = ints(groups[1])
        joints.append((p, c, idx, r, t))
    sph_blk = text[text.index('SPHERES[NS]={'):text.index('};', text.index('SPHERES[NS]={'))]
    spheres = []
    for line in sph_blk.splitlines()[1:]:
        line = line.strip()
        if not line.startswith('{'): continue
        link = int(line[1:line.index(',')])
        groups = re.findall(r'\{([^{}]*)\}', line)
        pos = ints(groups[0])
        after = line[line.index('}') + 2:]
        radius = int(after.split(',')[0])
        spheres.append((link, pos, radius))
    pairs = [tuple(map(int, m)) for m in re.findall(r'\{(\d+),(\d+)\}', text[text.index('SELF_PAIRS'):])]
    lo = ints(re.search(r'ANGLE_LO\[7\]=\{([^}]*)\}', text).group(1))
    hi = ints(re.search(r'ANGLE_HI\[7\]=\{([^}]*)\}', text).group(1))
    atan = ints(re.search(r'ATAN_Q28\[30\]=\{([^}]*)\}', text).group(1))
    assert len(joints) == 12 and len(spheres) == 59 and len(pairs) == 690 and len(atan) == 30

    def s(v, w):
        return f"-{w}'sd{-v}" if v < 0 else f"{w}'sd{v}"

    o = []
    o.append('// AUTO-GENERATED by golden/gen_consts.py from build/panda_generated.hh. Do not edit.')
    o.append('// Pinned Panda URDF/SRDF constants (Q30 rotations, Q24 translations, Q14 radii).')
    o.append('`timescale 1ns/1ps')
    o.append('module panda_consts (')
    o.append('  input  wire [3:0]  j_idx,        // joint 0..11')
    o.append('  output reg  [3:0]  j_parent,')
    o.append('  output reg  [3:0]  j_child,')
    o.append('  output reg  [3:0]  j_axis,       // 0..6 revolute joint index, 15 = fixed')
    o.append('  input  wire [3:0]  j_word,       // 0..8 rotation, 9..11 translation')
    o.append('  output reg  signed [35:0] j_val,')
    o.append('  input  wire [5:0]  s_idx,        // sphere 0..58')
    o.append('  output reg  [3:0]  s_link,')
    o.append('  input  wire [1:0]  s_axis,')
    o.append('  output reg  signed [35:0] s_pos,')
    o.append('  output reg  [15:0] s_radius,')
    o.append('  input  wire [4:0]  a_idx,')
    o.append('  output reg  signed [35:0] a_val,  // atan Q28')
    o.append('  input  wire [9:0]  p_idx,        // self-collision pair 0..689')
    o.append('  output reg  [5:0]  p_a,')
    o.append('  output reg  [5:0]  p_b,')
    o.append('  input  wire [2:0]  l_idx,')
    o.append('  output reg  signed [31:0] l_lo,')
    o.append('  output reg  signed [31:0] l_hi')
    o.append(');')
    o.append('  localparam NUM_JOINTS = 12, NUM_SPHERES = 59, NUM_PAIRS = 690;')
    o.append('  always @* begin')
    o.append('    j_parent = 0; j_child = 0; j_axis = 4\'d15;')
    o.append('    case (j_idx)')
    for k, (p, c, idx, r, t) in enumerate(joints):
        o.append(f"      4'd{k}: begin j_parent = 4'd{p}; j_child = 4'd{c}; j_axis = 4'd{idx if idx >= 0 else 15}; end")
    o.append('      default: ;')
    o.append('    endcase')
    o.append('  end')
    o.append('  always @* begin')
    o.append('    j_val = 36\'sd0;')
    o.append('    case ({j_idx, j_word})')
    for k, (p, c, idx, r, t) in enumerate(joints):
        for w, v in enumerate(r + t):
            if v: o.append(f"      8'd{k * 16 + w}: j_val = {s(v, 36)};")
    o.append('      default: ;')
    o.append('    endcase')
    o.append('  end')
    o.append('  always @* begin')
    o.append('    s_link = 0; s_radius = 0;')
    o.append('    case (s_idx)')
    for k, (link, pos, rad) in enumerate(spheres):
        o.append(f"      6'd{k}: begin s_link = 4'd{link}; s_radius = 16'd{rad}; end")
    o.append('      default: ;')
    o.append('    endcase')
    o.append('  end')
    o.append('  always @* begin')
    o.append('    s_pos = 36\'sd0;')
    o.append('    case ({s_idx, s_axis})')
    for k, (link, pos, rad) in enumerate(spheres):
        for a, v in enumerate(pos):
            if v: o.append(f"      8'd{k * 4 + a}: s_pos = {s(v, 36)};")
    o.append('      default: ;')
    o.append('    endcase')
    o.append('  end')
    o.append('  always @* begin')
    o.append('    case (a_idx)')
    for k, v in enumerate(atan):
        o.append(f"      5'd{k}: a_val = {s(v, 36)};")
    o.append("      default: a_val = 36'sd0;")
    o.append('    endcase')
    o.append('  end')
    o.append('  always @* begin')
    o.append('    case (p_idx)')
    for k, (a, b) in enumerate(pairs):
        o.append(f"      10'd{k}: begin p_a = 6'd{a}; p_b = 6'd{b}; end")
    o.append("      default: begin p_a = 6'd0; p_b = 6'd0; end")
    o.append('    endcase')
    o.append('  end')
    o.append('  always @* begin')
    o.append('    case (l_idx)')
    for k in range(7):
        o.append(f"      3'd{k}: begin l_lo = {s(lo[k], 32)}; l_hi = {s(hi[k], 32)}; end")
    o.append("      default: begin l_lo = 32'sd0; l_hi = 32'sd0; end")
    o.append('    endcase')
    o.append('  end')
    o.append('endmodule')
    # dedicated self-collision pair ROM: {a, b, R_a + R_b} (used by the 4-lane pair checker)
    o.append('')
    o.append('module panda_pairs (input wire [9:0] idx, output reg [5:0] a, output reg [5:0] b, output reg [15:0] rsum);')
    o.append('  always @* begin')
    o.append('    case (idx)')
    for k, (pa_, pb_) in enumerate(pairs):
        o.append(f"      10'd{k}: begin a = 6'd{pa_}; b = 6'd{pb_}; rsum = 16'd{spheres[pa_][2] + spheres[pb_][2]}; end")
    o.append("      default: begin a = 6'd0; b = 6'd0; rsum = 16'd0; end")
    o.append('    endcase')
    o.append('  end')
    o.append('endmodule')
    (HW / 'rtl' / 'panda_consts.v').write_text('\n'.join(o) + '\n')
    print('wrote rtl/panda_consts.v', len(joints), len(spheres), len(pairs))


if __name__ == '__main__':
    main()
